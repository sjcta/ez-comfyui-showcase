from pathlib import Path
import re
import unittest


ROOT = Path(__file__).resolve().parents[1]


class AudioHistoryUiTests(unittest.TestCase):
    def test_audio_history_cards_render_centered_wave_button(self):
        history_js = (ROOT / "static/js/modules/history.js").read_text()
        css = (ROOT / "static/css/style.css").read_text()
        sprite = (ROOT / "static/icons/sprite.svg").read_text()

        self.assertIn("explicit === 'audio'", history_js)
        self.assertIn("function _isAudioItem(item)", history_js)
        self.assertIn("function _infoAudioTagHtml(item)", history_js)
        self.assertIn("gi-audio-preview", history_js)
        self.assertIn("function toggleAudioCardPreview(event, button)", history_js)
        self.assertIn("function _audioPreviewFromTarget(target)", history_js)
        self.assertIn("window.CW.toggleAudioCardPreview = toggleAudioCardPreview;", history_js)
        self.assertIn("gi-audio-play", history_js)
        self.assertIn("gi-audio-canvas", history_js)
        self.assertIn("gi-audio-el", history_js)
        self.assertIn('CW.icon("audio-wave", 34)', history_js)
        self.assertIn('onclick="CW.toggleAudioCardPreview(event,this)"', history_js)
        self.assertIn('tabindex="-1"', history_js)
        self.assertIn("data-audio-disabled", history_js)
        self.assertIn("if (audio.ended)", history_js)
        self.assertIn("audio.currentTime = 0", history_js)
        self.assertNotIn("<audio controls", history_js)
        self.assertNotIn("gi-audio-mark", history_js)
        self.assertIn("return '语音TTS';", history_js)
        self.assertIn(".gi-audio-preview", css)
        self.assertIn(".gi-audio-play", css)
        self.assertIn(".gi-audio-canvas", css)
        self.assertIn(".gi-audio-preview:focus-visible", css)
        self.assertIn(".gi-audio-play:focus", css)
        self.assertIn(".gi-audio-preview.is-disabled", css)
        self.assertIn(".gi:not(.job-card) .gi-audio-preview", css)
        self.assertIn("bottom: var(--gi-info-height, 78px);", css)
        audio_button_css = re.search(r"\.gi-audio-play\s*\{(?P<body>.*?)\n\}", css, re.S)
        audio_icon_css = re.search(r"\.gi-audio-play \.cw-icon\s*\{(?P<body>.*?)\n\}", css, re.S)
        self.assertIsNotNone(audio_button_css)
        self.assertIsNotNone(audio_icon_css)
        self.assertIn("width: 44px;", audio_button_css.group("body"))
        self.assertIn("height: 44px;", audio_button_css.group("body"))
        self.assertIn("width: 34px;", audio_icon_css.group("body"))
        self.assertIn("height: 34px;", audio_icon_css.group("body"))
        self.assertIn("function _audioPreviewCanvasHtml()", history_js)
        self.assertIn("function _ensureAudioCardVisualizer(audio, preview)", history_js)
        self.assertIn("createMediaElementSource(audio)", history_js)
        self.assertIn("getByteFrequencyData", history_js)
        self.assertIn("getByteTimeDomainData", history_js)
        self.assertIn("requestAnimationFrame", history_js)
        self.assertIn("var playPromise = audio.play();", history_js)
        self.assertNotIn("then(function() { return audio.play(); })", history_js)
        self.assertIn("fadeAlpha", history_js)
        self.assertIn("fadeTarget", history_js)
        self.assertIn("function _advanceAudioVizFade(viz)", history_js)
        self.assertIn("viz.preview.classList.remove('is-visualizing')", history_js)
        self.assertIn("_drawAudioCardStars", history_js)
        self.assertIn("_drawAudioCardAverage", history_js)
        self.assertIn("_drawAudioCardWaveform", history_js)
        self.assertIn(".gi-audio-preview.is-playing .gi-audio-canvas", css)
        self.assertIn(".gi-audio-preview.is-visualizing .gi-audio-canvas", css)
        self.assertIn("transition: opacity .42s ease;", css)
        self.assertNotIn("gi-audio-viz", history_js)
        self.assertNotIn(".gi-audio-viz", css)
        self.assertNotIn(".gi-audio-play::before", css)
        self.assertNotIn(".gi-audio-play::after", css)
        self.assertNotIn("gi-audio-viz-icon", css)
        self.assertNotIn("gi-audio-viz-pulse-ring", css)
        self.assertNotIn("gi-audio-wave-motion", history_js)
        self.assertNotIn(".gi-audio-play:hover:not(:disabled)", css)
        self.assertIn(".gi-audio-el", css)
        self.assertNotIn(".gi-audio-mark", css)
        self.assertIn(".wf-tag-audio", css)
        self.assertIn('id="icon-audio-wave"', sprite)
        self.assertIn("'.gi-video-poster, .gi-audio-preview'", history_js)


if __name__ == "__main__":
    unittest.main()
